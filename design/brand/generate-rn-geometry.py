"""Generate src/components/brand/quizVibeBrandGeometry.ts from the brand SVGs.

usage (from repo root): python -I design/brand/generate-rn-geometry.py

The finalized SVGs in design/brand/ are the source of truth. This script
copies their paint-free geometry (path data + viewBoxes) into a TypeScript
module so react-native-svg can render exactly the same shapes. Colours live
in the React components, not here. Re-run after any change to the SVGs.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BRAND = os.path.join(ROOT, 'design', 'brand')
OUT = os.path.join(ROOT, 'src', 'components', 'brand', 'quizVibeBrandGeometry.ts')


def read(name):
    return open(os.path.join(BRAND, name), encoding='utf-8').read()


def viewbox(svg):
    return [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]


mark = read('quizvibe-mark.svg')
word = read('quizvibe-wordmark.svg')

parts = dict(re.findall(r'<path id="qvm-([a-z0-9]+)" d="([^"]+)"', mark))
ring, connector, handle = parts['ring'], parts['connector'], parts['handle']
arcs = [parts[k] for k in sorted(p for p in parts if p.startswith('arc'))]
word_d = re.search(r'<g id="qvw-geometry"[^>]*><path d="([^"]+)"', word).group(1)
mvb, wvb = viewbox(mark), viewbox(word)

assert len(arcs) == 3, arcs


def ts_str(s):
    return "'" + s.replace("'", "\\'") + "'"


lines = [
    '// AUTO-GENERATED by design/brand/generate-rn-geometry.py from the',
    '// finalized brand SVGs in design/brand/. Do not edit by hand -- change the',
    '// SVGs and re-run the script. Geometry only (no colours).',
    '',
    'export const MARK_VIEWBOX = { width: %s, height: %s } as const;' % (mvb[2], mvb[3]),
    '',
    'export const MARK_PATHS = {',
    f'  ring: {ts_str(ring)},',
    '  arcs: [',
    *[f'    {ts_str(a)},' for a in arcs],
    '  ],',
    f'  connector: {ts_str(connector)},',
    f'  handle: {ts_str(handle)},',
    '} as const;',
    '',
    'export const WORDMARK_VIEWBOX = { width: %s, height: %s } as const;' % (wvb[2], wvb[3]),
    '',
    '/** "QuizVibe" in Manrope Bold, as outlines. */',
    f'export const WORDMARK_PATH = {ts_str(word_d)};',
    '',
]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('wrote', os.path.relpath(OUT, ROOT))
